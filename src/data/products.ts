export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getRelatedProducts(currentId: string, category: string, limit = 3): Product[] {
  return PRODUCTS.filter((p) => p.id !== currentId && p.category === category)
    .concat(PRODUCTS.filter((p) => p.id !== currentId && p.category !== category))
    .slice(0, limit);
}

export function formatPrice(price: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(price);
}
